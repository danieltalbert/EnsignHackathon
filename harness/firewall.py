"""OS firewall changes behind isolate / block address / close port. All reversible, all need admin.

macOS: pf rules in our own anchor (com.apple/sentinel). Apple's stock /etc/pf.conf already
       evaluates com.apple/*, so the system file is never edited.
Linux: one nftables table (inet sentinel), replaced atomically, deleted on undo.
Windows: Windows Firewall rules all named "Sentinel"; isolation flips the default outbound
       policy to block and restores the previous policy on undo.
The desired state lives in harness/state/firewall.json and the OS config is rebuilt from it,
so every change has an exact undo.
"""
import os, re, json, copy, socket, shutil, ipaddress, subprocess
from urllib.parse import urlparse
from . import config, elevate
from .elevate import q

STATE = config.STATE_DIR / "firewall.json"
EMPTY = {"isolated": False, "allow": [], "blocked": [], "ports": [], "token": None, "win_prev": None}
GEMINI_HOST = "generativelanguage.googleapis.com"


def load():
    try:
        return {**EMPTY, **json.loads(STATE.read_text())}
    except (OSError, ValueError):
        return dict(EMPTY)


def _save(s):
    config.STATE_DIR.mkdir(parents=True, exist_ok=True)
    tmp = STATE.with_suffix(".tmp")
    tmp.write_text(json.dumps(s, indent=1), encoding="utf-8")
    os.replace(tmp, STATE)


def resolve(host):
    try:
        return sorted({ai[4][0].split("%")[0] for ai in socket.getaddrinfo(host, None)})
    except (OSError, UnicodeError):
        return []


def endpoint_ips():
    """Addresses that must stay reachable while isolated: the model endpoint (and Gemini)."""
    hosts = [urlparse(config.OLLAMA_URL).hostname] + ([GEMINI_HOST] if config.GEMINI_API_KEY else [])
    return sorted({ip for h in hosts if h for ip in resolve(h)})


def addresses(raw):
    """Finding-supplied hosts/IPs -> validated IPs to block. Never the model endpoint or this machine."""
    keep = set(endpoint_ips())
    out = []
    for item in raw or []:
        host = str(item).strip()
        if not re.fullmatch(r"[A-Za-z0-9.:%\-\[\]]{1,253}", host):
            raise ValueError(f"'{host[:60]}' is not an address Sentinel will block.")
        try:
            ips = [str(ipaddress.ip_address(host.strip("[]").split("%")[0]))]
        except ValueError:
            ips = resolve(host)
        for ip in ips:
            a = ipaddress.ip_address(ip)
            if a.is_loopback or a.is_unspecified or a.is_multicast or ip in keep:
                continue
            out.append(ip)
    if not out:
        raise ValueError("No blockable address in this finding (loopback, the model endpoint, or unresolvable).")
    return sorted(set(out))


def ports(raw):
    out = sorted({int(p) for p in raw or [] if str(p).isdigit() and 0 < int(p) < 65536})
    if not out:
        raise ValueError("No valid port in this finding.")
    return out


def plan(op, values=None):
    old = load()
    new = copy.deepcopy(old)
    if op == "isolate":
        new["isolated"], new["allow"] = True, endpoint_ips()
    elif op == "undo_isolation":
        new["isolated"], new["allow"] = False, []
    elif op == "block":
        new["blocked"] = sorted(set(new["blocked"]) | set(values))
    elif op == "unblock":
        new["blocked"] = sorted(set(new["blocked"]) - set(values))
    elif op == "close_port":
        new["ports"] = sorted(set(new["ports"]) | set(values))
    elif op == "reopen_port":
        new["ports"] = sorted(set(new["ports"]) - set(values))
    return old, new


def _empty(s):
    return not (s["isolated"] or s["blocked"] or s["ports"])


# --- rule builders (pure; covered by selftest) ---------------------------------

def pf_rules(s):
    v = lambda xs: ", ".join(str(x) for x in xs)
    lines = ["# Generated by Sentinel. Loaded into anchor com.apple/sentinel only."]
    if s["blocked"]:
        lines.append(f"table <sentinel_block> {{ {v(s['blocked'])} }}")
    if s["isolated"] and s["allow"]:
        lines.append(f"table <sentinel_allow> {{ {v(s['allow'])} }}")
    if s["blocked"]:
        lines += ["block drop out quick to <sentinel_block>", "block drop in quick from <sentinel_block>"]
    if s["ports"]:
        lines.append(f"block drop in quick on ! lo0 proto {{ tcp, udp }} to any port {{ {v(s['ports'])} }}")
    if s["isolated"]:
        lines += ["pass quick on lo0 all",
                  "pass out quick proto { tcp, udp } to any port 53 keep state",
                  "pass out quick proto udp from any port 68 to any port 67 keep state",
                  "pass in quick proto udp from any port 67 to any port 68 keep state",
                  "pass quick inet6 proto icmp6 all"]
        if s["allow"]:
            lines += ["pass out quick to <sentinel_allow> flags any keep state",
                      "pass in quick from <sentinel_allow> flags any keep state"]
        lines.append("block drop quick all")
    return "\n".join(lines) + "\n"


def nft_rules(s):
    v4 = lambda xs: [x for x in xs if ":" not in x]
    v6 = lambda xs: [x for x in xs if ":" in x]
    sets, inp, out = [], [], []
    for name, ips in (("block4", v4(s["blocked"])), ("block6", v6(s["blocked"])),
                      ("allow4", v4(s["allow"]) if s["isolated"] else []),
                      ("allow6", v6(s["allow"]) if s["isolated"] else [])):
        if ips:
            kind = "ipv4_addr" if name.endswith("4") else "ipv6_addr"
            sets.append(f"  set {name} {{ type {kind}; elements = {{ {', '.join(ips)} }} }}")
    has = lambda n: any(f"set {n} " in x for x in sets)
    if has("block4"):
        inp.append("ip saddr @block4 drop"); out.append("ip daddr @block4 drop")
    if has("block6"):
        inp.append("ip6 saddr @block6 drop"); out.append("ip6 daddr @block6 drop")
    if s["ports"]:
        p = ", ".join(map(str, s["ports"]))
        inp += [f'iifname != "lo" tcp dport {{ {p} }} drop', f'iifname != "lo" udp dport {{ {p} }} drop']
    if s["isolated"]:
        inp += ['iifname "lo" accept', "udp sport 53 accept", "tcp sport 53 accept",
                "udp sport 67 udp dport 68 accept", "meta l4proto ipv6-icmp accept"]
        out += ['oifname "lo" accept', "udp dport 53 accept", "tcp dport 53 accept",
                "udp sport 68 udp dport 67 accept", "meta l4proto ipv6-icmp accept"]
        if has("allow4"):
            inp.append("ip saddr @allow4 accept"); out.append("ip daddr @allow4 accept")
        if has("allow6"):
            inp.append("ip6 saddr @allow6 accept"); out.append("ip6 daddr @allow6 accept")
        inp.append("drop"); out.append("drop")
    chain = lambda name, hook, rules: ([f"  chain {name} {{", f"    type filter hook {hook} priority 0; policy accept;"]
                                       + [f"    {r}" for r in rules] + ["  }"])
    body = ["table inet sentinel", "delete table inet sentinel", "table inet sentinel {", *sets,
            *chain("input", "input", inp), *chain("output", "output", out), "}"]
    return "\n".join(body) + "\n"


def win_policy():
    """Current Windows Firewall state/policy per profile, so undo can restore it."""
    try:
        out = subprocess.run(["netsh", "advfirewall", "show", "allprofiles"],
                             capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.TimeoutExpired):
        out = ""
    prev = {}
    for prof, state, policy in re.findall(r"(Domain|Private|Public) Profile Settings:.*?State\s+(\w+).*?"
                                          r"Firewall Policy\s+(\S+)", out, re.S):
        prev[prof.lower()] = {"state": state.lower(), "policy": policy.lower()}
    return prev or {p: {"state": "on", "policy": "blockinbound,allowoutbound"} for p in ("domain", "private", "public")}


def netsh_lines(old, new):
    rule = 'netsh advfirewall firewall add rule name="Sentinel" '
    lines = ['?netsh advfirewall firewall delete rule name="Sentinel"']
    for ip in new["blocked"]:
        lines += [rule + f"dir=out action=block remoteip={ip}", rule + f"dir=in action=block remoteip={ip}"]
    for port in new["ports"]:
        lines += [rule + f"dir=in action=block protocol={p} localport={port}" for p in ("TCP", "UDP")]
    if new["isolated"]:
        lines += ["netsh advfirewall set allprofiles state on",
                  "netsh advfirewall set allprofiles firewallpolicy blockinbound,blockoutbound",
                  rule + "dir=out action=allow protocol=UDP remoteport=53",
                  rule + "dir=out action=allow protocol=TCP remoteport=53",
                  rule + "dir=out action=allow protocol=UDP localport=68 remoteport=67"]
        if new["allow"]:
            lines.append(rule + f"dir=out action=allow remoteip={','.join(new['allow'])}")
    elif old["isolated"]:
        for prof, p in (old.get("win_prev") or {}).items():
            lines += [f"netsh advfirewall set {prof}profile firewallpolicy {p['policy']}",
                      f"netsh advfirewall set {prof}profile state {p['state']}"]
    return lines


# --- apply ----------------------------------------------------------------------

def apply(old, new, why):
    """Make the OS firewall match `new` with one consent prompt, then save it. Returns output."""
    config.STATE_DIR.mkdir(parents=True, exist_ok=True)
    if config.OS == "macos":
        pf = "/sbin/pfctl -a com.apple/sentinel"
        if _empty(new):
            script = f"{pf} -F rules 2>&1; {pf} -F Tables 2>&1"
            if old.get("token"):
                script += f"; /sbin/pfctl -X {int(old['token'])} 2>&1"
            script += "; exit 0"
        else:
            rules = config.STATE_DIR / "pf.rules"
            rules.write_text(pf_rules(new), encoding="utf-8")
            os.chmod(rules, 0o600)
            script = f"{pf} -f {q(rules)} 2>&1" + ("" if old.get("token") else " && /sbin/pfctl -E 2>&1")
            if new["isolated"] and not old["isolated"]:
                script += " && /sbin/pfctl -F states 2>&1"  # drop connections opened before isolation
            for ip in set(new["blocked"]) - set(old["blocked"]):
                script += f"; /sbin/pfctl -k {q(ip)} 2>&1; /sbin/pfctl -k {'::/0' if ':' in ip else '0.0.0.0/0'} -k {q(ip)} 2>&1"
        rc, out = elevate.run(script, why)
        if rc:
            raise RuntimeError(out[-300:] or f"pfctl exited with {rc}")
        m = re.search(r"Token : (\d+)", out)
        new["token"] = None if _empty(new) else (old.get("token") or (m.group(1) if m else None))
    elif config.OS == "linux":
        nft = shutil.which("nft") or next((p for p in ("/usr/sbin/nft", "/sbin/nft") if os.path.exists(p)), None)
        if not nft:
            raise elevate.Unsupported("nftables (nft) isn't installed, so firewall actions aren't available here.")
        if _empty(new):
            script = f"{nft} delete table inet sentinel 2>/dev/null; exit 0"
        else:
            rules = config.STATE_DIR / "sentinel.nft"
            rules.write_text(nft_rules(new), encoding="utf-8")
            os.chmod(rules, 0o600)
            script = f"{nft} -f {q(rules)}"
        rc, out = elevate.run(script, why)
        if rc:
            raise RuntimeError(out[-300:] or f"nft exited with {rc}")
    elif config.OS == "windows":
        if new["isolated"] and not old["isolated"]:
            new["win_prev"] = win_policy()
        rc, out = elevate.run(netsh_lines(old, new), why)
        if rc:
            raise RuntimeError(out[-300:] or f"netsh exited with {rc}")
        if not new["isolated"]:
            new["win_prev"] = None
    else:
        raise elevate.Unsupported("Not supported on this OS yet.")
    _save(new)
    return out
